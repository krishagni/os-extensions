-- MySQL
CREATE TABLE VISIT_SPECIMEN_TYPE_SUMMARY (
    IDENTIFIER        BIGINT AUTO_INCREMENT PRIMARY KEY,
    VISIT_ID          BIGINT NOT NULL,
    SPECIMEN_TYPE     VARCHAR(255),
    COUNT_OF_ALIQUOTS BIGINT,
    COLLECTION_AGE    BIGINT,
    STORED_STATUS     VARCHAR(50),
    
    CONSTRAINT fk_vs_summary_visit 
        FOREIGN KEY (VISIT_ID) 
        REFERENCES CATISSUE_SPECIMEN_COLL_GROUP (IDENTIFIER)
);

-- Indexes on all fields
CREATE INDEX idx_vs_summary_visit_id 
    ON VISIT_SPECIMEN_TYPE_SUMMARY (VISIT_ID);

CREATE INDEX idx_vs_summary_sp_type 
    ON VISIT_SPECIMEN_TYPE_SUMMARY (SPECIMEN_TYPE);

CREATE INDEX idx_vs_summary_alq_count 
    ON VISIT_SPECIMEN_TYPE_SUMMARY (COUNT_OF_ALIQUOTS);

CREATE INDEX idx_vs_summary_age_at_coll 
    ON VISIT_SPECIMEN_TYPE_SUMMARY (COLLECTION_AGE);

CREATE INDEX idx_vs_summary_stored_status 
    ON VISIT_SPECIMEN_TYPE_SUMMARY (STORED_STATUS);

